    def questionsGenerate(self, level: int, trainingType: TrainingType) -> list:
        levelInfo = self.levels.get(level, None)
        if levelInfo is None: return []
        match trainingType:
            case TrainingType.LETTER:
                questions = levelInfo['letters'] * levelInfo['letter_training_count'] + levelInfo['new_letters']
                randomShuffle(questions)
                return questions
            case TrainingType.WORD:
                questions = levelInfo['words']
                randomShuffle(questions)
                cnt = levelInfo['words_training_count']
                return questions[:cnt]
            case TrainingType.PHRASE:
                questions = levelInfo.get('phrases', [])
                randomShuffle(questions)
                cnt = levelInfo.get('phrases_training_count', 0)
                return questions[:cnt]
            
